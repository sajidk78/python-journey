name= "  sajid ali"

print("\n Original Name:")
print(name)
print("\n Uppercase:")
print(name.upper())
print("\n Lowercase:")
print(name.lower())
print("\n Clean Name:")
print(name.strip())
print("\n Title:")
print(name.strip().title())

clean_name=name.strip().title()
print("\n Length: ")
print(len(clean_name))
